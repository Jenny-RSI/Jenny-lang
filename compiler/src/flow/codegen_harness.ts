import type { ModuleAST } from "./ast.ts";
import {
  cFnName,
  isClosureType,
  isStructPtrType,
  loadStdFuzzHarnesses,
  mapCType,
  resultTypedefName,
  translateExpr,
} from "./codegen_expr.ts";

function stripPtrAndOpt(ty: string): string {
  return ty.replace(/^[*^]+/, "").replace(/\?+$/, "");
}

export function emitJniHeaderFirewall(ast: ModuleAST, abiHash: string): string {
  const guardMacro = `JENNY_FIREWALL_${ast.name.toUpperCase()}_H`;
  const lines: string[] = [
    `/* Auto-generated by Jenny .jni ABI Header Firewall (abi_hash=${abiHash}) */`,
    `#ifndef ${guardMacro}`,
    `#define ${guardMacro}`,
    '#include "../../compiler/jenny-flow/jenny_rt.h"',
    "",
  ];
  for (const [sname, sdecl] of Object.entries(ast.structs)) {
    const kw = sdecl.is_union ? "union" : "struct";
    lines.push(`typedef ${kw} ${sname} {`);
    for (const f of sdecl.fields) {
      const mArr = /^\[(\d+)\](.+)$/.exec(f.ty);
      if (mArr) {
        lines.push(`    ${mapCType(mArr[2])} ${f.name}[${mArr[1]}];`);
      } else if (f.bit_width !== null) {
        lines.push(`    ${mapCType(f.ty)} ${f.name} : ${f.bit_width};`);
      } else {
        lines.push(`    ${mapCType(f.ty)} ${f.name};`);
      }
    }
    lines.push(`} ${sname};`);
    lines.push("");
  }
  for (const fspec of Object.values(ast.functions)) {
    if (fspec.is_spin_variadic) {
      continue;
    }
    const cname = cFnName(fspec);
    if (fspec.err_ty) {
      const rname = resultTypedefName(fspec);
      lines.push(`typedef struct { bool is_err; JnAnyError err; ${mapCType(fspec.ret_ty)} val; } ${rname};`);
    }
    const retC = fspec.err_ty ? resultTypedefName(fspec) : mapCType(fspec.ret_ty);
    const cParams: string[] = [];
    for (const p of fspec.params) {
      if (p.name === "self") {
        cParams.push(p.mode === "mut" ? `${p.ty}* JN_RESTRICT self` : `const ${p.ty}* self`);
      } else if (isStructPtrType(p.ty)) {
        cParams.push(`${mapCType(p.ty)} ${p.name}`);
      } else if (p.mode === "mut" && (p.ty === "Arena" || p.ty in ast.structs)) {
        cParams.push(`${mapCType(p.ty)}* JN_RESTRICT ${p.name}`);
      } else {
        cParams.push(`${mapCType(p.ty)} ${p.name}`);
      }
    }
    const paramSig = cParams.length > 0 ? cParams.join(", ") : "void";
    lines.push(`${retC} ${cname}(${paramSig});`);
  }
  lines.push("");
  lines.push(`#endif /* ${guardMacro} */`);
  return lines.join("\n") + "\n";
}

export function emitExampleRunnersAndFuzzSuite(
  ast: ModuleAST,
  out: string[],
  headerInsertIdx: number,
  liftedClosuresDefs: string[],
): void {
  // 5. Emit @example test runners and main()
  for (let idx = 0; idx < ast.examples.length; idx++) {
    const ex = ast.examples[idx];
    out.push(`static void run_example_${idx}(void) {`);
    let bIdx = 0;
    const exPtrVars = new Set<string>();
    const exVarTypes: Record<string, string> = {};
    const exLines = ex.body_lines.map((l) => l.trim()).filter((l) => l.length > 0);

    while (bIdx < exLines.length) {
      const stmt = exLines[bIdx];

      if (stmt.startsWith("while ") && stmt.endsWith("{")) {
        const wCond = stmt.slice("while ".length, -1).trim();
        out.push(`    while (${translateExpr(wCond, ast, null, null, exPtrVars, exVarTypes)}) {`);
        bIdx += 1;
        continue;
      }
      if (stmt === "}") {
        out.push("    }");
        bIdx += 1;
        continue;
      }

      const mAssertIs = /^assert\(([A-Za-z0-9_]+)\s+is\s+(?:Err\(([A-Za-z0-9_.]+)\)|([A-Za-z0-9_.]+))\)$/.exec(stmt);
      if (mAssertIs) {
        const vname = mAssertIs[1];
        const errVariant = mAssertIs[2] || mAssertIs[3];
        const expectedTag = translateExpr(errVariant, ast, null, null, exPtrVars, exVarTypes);
        const escaped = stmt.replaceAll('"', '\\"');
        out.push(
          `    if (!(${vname}.is_err && ${vname}.err.err_tag == ${expectedTag})) jn_contract_fail("example_assert", "example_${idx}", "${escaped}");`,
        );
        bIdx += 1;
        continue;
      }

      const mAssert = /^assert\((.+)\)$/.exec(stmt);
      if (mAssert) {
        let inner = mAssert[1].trim();
        inner = inner.replace(/([A-Za-z0-9_.]+\([^)]*\))[!?]/g, "$1.val");
        const cInner = translateExpr(inner, ast, null, null, exPtrVars, exVarTypes);
        const escaped = stmt.replaceAll('"', '\\"');
        out.push(
          `    if (!(${cInner})) jn_contract_fail("example_assert", "example_${idx}", "${escaped}");`,
        );
        bIdx += 1;
        continue;
      }

      const mUnwrapDecl = /^(?:val|var)\s+([A-Za-z0-9_]+)\s*=\s*(.+)[!?]$/.exec(stmt);
      if (mUnwrapDecl) {
        let vname = mUnwrapDecl[1];
        if (vname === "_") {
          vname = `_ign_${bIdx}`;
        }
        const callExpr = mUnwrapDecl[2].trim();
        const cCall = translateExpr(callExpr, ast, null, null, exPtrVars, exVarTypes);
        const fnPrefix = cCall.split("(")[0].trim();
        const matchedSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === fnPrefix);
        if (!matchedSpec) {
          throw new Error(`Cannot resolve fallible function in example: ${fnPrefix}`);
        }
        const resTy = resultTypedefName(matchedSpec);
        const valTy = mapCType(matchedSpec.ret_ty);
        exVarTypes[vname] = isClosureType(matchedSpec.ret_ty)
          ? matchedSpec.ret_ty
          : stripPtrAndOpt(matchedSpec.ret_ty);
        if (isStructPtrType(matchedSpec.ret_ty)) {
          exPtrVars.add(vname);
        }
        out.push(`    ${resTy} _u_${vname} = ${cCall};`);
        out.push(`    if (_u_${vname}.is_err) jn_contract_fail("unwrap_err", "example_${idx}", "${vname}");`);
        out.push(`    ${valTy} ${vname} = _u_${vname}.val;`);
        bIdx += 1;
        continue;
      }

      if (stmt.endsWith("!") || stmt.endsWith("?")) {
        const callExpr = stmt.slice(0, -1).trim();
        const cCall = translateExpr(callExpr, ast, null, null, exPtrVars, exVarTypes);
        out.push(`    if ((${cCall}).is_err) jn_contract_fail("unwrap_err", "example_${idx}", "stmt");`);
        bIdx += 1;
        continue;
      }

      const mDecl = /^(?:val|var)\s+([A-Za-z0-9_]+)(?:\s*:\s*([^=]+))?\s*=\s*(.+)$/.exec(stmt);
      if (mDecl) {
        let vname = mDecl[1];
        if (vname === "_") {
          vname = `_ign_${bIdx}`;
        }
        const explTy = mDecl[2] ? mDecl[2].trim() : null;
        const rhs = mDecl[3].trim();
        const cRhs = translateExpr(rhs, ast, null, null, exPtrVars, exVarTypes);
        const fnPrefix = cRhs.split("(")[0].trim();
        const matchedSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === fnPrefix) ?? null;
        let cTy: string;
        if (explTy) {
          cTy = mapCType(explTy);
          exVarTypes[vname] = isClosureType(explTy) ? explTy : stripPtrAndOpt(explTy);
          if (isStructPtrType(explTy)) {
            exPtrVars.add(vname);
          }
        } else if (rhs.startsWith("Arena.new")) {
          cTy = "JnArena";
          exVarTypes[vname] = "Arena";
        } else if (matchedSpec) {
          cTy = matchedSpec.err_ty ? resultTypedefName(matchedSpec) : mapCType(matchedSpec.ret_ty);
          if (!matchedSpec.err_ty) {
            exVarTypes[vname] = isClosureType(matchedSpec.ret_ty)
              ? matchedSpec.ret_ty
              : stripPtrAndOpt(matchedSpec.ret_ty);
            if (isStructPtrType(matchedSpec.ret_ty)) {
              exPtrVars.add(vname);
            }
          }
        } else if (cRhs.startsWith("((JnTuple_i64_FmtSpec_i64)")) {
          cTy = "JnTuple_i64_FmtSpec_i64";
          exVarTypes[vname] = "(i64, FmtSpec, i64)";
        } else if (cRhs.startsWith("((JnTuple_i64_FmtSpec)")) {
          cTy = "JnTuple_i64_FmtSpec";
          exVarTypes[vname] = "(i64, FmtSpec)";
        } else if (
          cRhs.startsWith("JnString_") ||
          cRhs.startsWith("jn_raw_to_sso_string") ||
          cRhs.startsWith("jn_fmt_end(")
        ) {
          cTy = "JnString";
          exVarTypes[vname] = "String";
        } else if (
          (cRhs.includes("jn_mk_str(") || cRhs.startsWith("jn_str_sub(") || cRhs.startsWith("jn_str_slice(")) &&
          !cRhs.startsWith("jn_raw_") &&
          !cRhs.startsWith("jn_string_") &&
          !cRhs.startsWith("jn_str_eq(")
        ) {
          cTy = "jn_str";
          exVarTypes[vname] = "str";
        } else {
          cTy = "int32_t";
        }
        out.push(`    ${cTy} ${vname} = ${cRhs};`);
        bIdx += 1;
        continue;
      }

      out.push(`    ${translateExpr(stmt, ast, null, null, exPtrVars, exVarTypes)};`);
      bIdx += 1;
    }

    const escapedTitle = ex.title.replaceAll('"', '\\"');
    out.push(`    printf("[PASS] %s (sizeof(JnAnyError)=%zu)\\n", "${escapedTitle}", sizeof(JnAnyError));`);
    out.push("}");
    out.push("");
  }

  if (liftedClosuresDefs.length > 0) {
    out.splice(headerInsertIdx, 0, ...liftedClosuresDefs);
  }

  // 6. Synthesize Contract-Driven Property-Based & Stateful Container Fuzzing Suite (`--fuzz v2`, target == -2)
  out.push("static void run_contract_fuzz_suite(void) {");
  out.push("    static const int64_t _bvals[16] = {-100, -10, -1, 0, 1, 2, 3, 4, 6, 8, 10, 16, 32, 50, 64, 100};");
  out.push("    uint64_t _seed = 0x9E3779B97F4A7C15ULL;");
  out.push("    int _scalar_calls = 0;");
  out.push("    int _stateful_calls = 0;");
  out.push("    int _example_replays = 0;");
  const scalarTys = new Set(["i64", "i32", "u32", "u16", "u8", "usize", "bool"]);
  for (const fspec of Object.values(ast.functions)) {
    if (
      !fspec.struct_owner &&
      !fspec.name.startsWith("rt_") &&
      !fspec.params.some((p) => p.name === "raw_ptr" || p.name === "ptr" || p.name === "dst_ptr" || p.name === "src_ptr") &&
      fspec.params.length > 0 &&
      fspec.params.every((p) => scalarTys.has(p.ty) && p.mode === "borrow") &&
      (scalarTys.has(fspec.ret_ty) || fspec.ret_ty === "void") &&
      (fspec.requires.length > 0 || fspec.ensures.length > 0)
    ) {
      const cname = cFnName(fspec);
      out.push("    for (int _i = 0; _i < 100; ++_i) {");
      const argNames: string[] = [];
      const fVarTypes: Record<string, string> = {};
      for (let pIdx = 0; pIdx < fspec.params.length; pIdx++) {
        const p = fspec.params[pIdx];
        out.push("        _seed ^= _seed >> 12; _seed ^= _seed << 25; _seed ^= _seed >> 27;");
        const cPty = mapCType(p.ty);
        if (p.ty === "bool") {
          out.push(`        ${cPty} ${p.name} = (_i + ${pIdx}) % 2 == 0;`);
        } else {
          out.push(
            `        ${cPty} ${p.name} = (${cPty})((_i < 16) ? _bvals[(_i + ${pIdx} * 3) & 15] : (int64_t)((_seed * 0x2545F4914F6CDD1DULL) % 120ULL) - 20);`,
          );
        }
        argNames.push(p.name);
        fVarTypes[p.name] = p.ty;
      }
      const hardConds: string[] = [];
      for (const req of fspec.requires) {
        if (!(req.else_err && fspec.err_ty)) {
          const cCond = translateExpr(req.cond, ast, fspec, null, new Set<string>(), fVarTypes);
          hardConds.push(`(${cCond})`);
        }
      }
      const callStr = `${cname}(${argNames.join(", ")})`;
      if (hardConds.length > 0) {
        out.push(`        if (${hardConds.join(" && ")}) { (void)${callStr}; _scalar_calls++; }`);
      } else {
        out.push(`        (void)${callStr}; _scalar_calls++;`);
      }
      out.push("    }");
    }
  }

  // Stateful Container Method-Sequence Fuzzing loaded from `library/std/fuzz_harnesses.json`
  const stdFuzzMap = loadStdFuzzHarnesses();
  if (ast.name in stdFuzzMap) {
    out.push(...stdFuzzMap[ast.name]);
  }

  out.push("    for (int _s = 0; _s < 20; ++_s) {");
  for (let idx = 0; idx < ast.examples.length; idx++) {
    out.push(`        run_example_${idx}();`);
    out.push("        _example_replays++;");
  }
  out.push("        jn_gc_collect_all();");
  out.push(
    `        if (jn_active_native_boxes() != 0) jn_contract_fail("fuzz_leak_audit", "${ast.name}", "active_native_boxes() == 0");`,
  );
  out.push("    }");
  out.push(
    `    printf("[FUZZ-PASS] module=%s vectors=%d scalar_calls=%d stateful_calls=%d example_replays=%d leak_check=%lld\\n", "${ast.name}", _scalar_calls + _stateful_calls + _example_replays, _scalar_calls, _stateful_calls, _example_replays, (long long)jn_active_native_boxes());`,
  );
  out.push("}");
  out.push("");

  out.push("int main(int argc, char** argv) {");
  out.push("    int target = (argc > 1) ? atoi(argv[1]) : -1;");
  out.push("    if (target == -2) { run_contract_fuzz_suite(); return 0; }");
  for (let idx = 0; idx < ast.examples.length; idx++) {
    out.push(`    if (target == -1 || target == ${idx}) run_example_${idx}();`);
  }
  out.push("    return 0;");
  out.push("}");
}
