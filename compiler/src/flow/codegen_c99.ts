import type { FnSpec, ModuleAST } from "./ast.ts";
import { cFnName, isClosureType, isStructPtrType, mapCType, parseStructFieldInits, resultTypedefName, translateExpr } from "./codegen_expr.ts";
import { emitExampleRunnersAndFuzzSuite } from "./codegen_harness.ts";

const stripPtrAndOpt = (ty: string): string => ty.replace(/^[*^]+/, "").replace(/\?+$/, "");
const removeFromList = (arr: string[], item: string): void => {
  const idx = arr.indexOf(item);
  if (idx !== -1) arr.splice(idx, 1);
};

export function transpileModuleToC99(ast: ModuleAST): string {
  const out: string[] = [
    "/* Auto-generated by Jenny-Native v1.0 C99 Transpiler (.jenny-cache/c99) */",
    '#include "../../compiler/jenny-flow/jenny_rt.h"',
    "",
    "typedef enum {",
    "    ErrTag_None = 0,",
  ];

  for (const [ename, edecl] of Object.entries(ast.enums)) {
    for (const v of edecl.variants) out.push(`    ErrTag_${ename}_${v},`);
  }
  out.push("} JnErrTag;");
  for (const ename of Object.keys(ast.enums)) out.push(`typedef int64_t ${ename};`);
  const emittedTuples = new Set<string>();
  for (const fn of Object.values(ast.functions)) {
    for (const p of fn.params) {
      const pty = p.ty.trim();
      if (pty.startsWith("(") && pty.endsWith(")")) {
        const tCname = mapCType(pty);
        if (!emittedTuples.has(tCname)) {
          emittedTuples.add(tCname);
          const tElems = pty.slice(1, -1).split(",").map((x) => x.trim()).filter((x) => x.length > 0);
          out.push(`typedef struct { ${tElems.map((te, idx) => `${mapCType(te)} f${idx};`).join(" ")} } ${tCname};`);
        }
      }
    }
  }
  out.push("");

  for (const [sname, sdecl] of Object.entries(ast.structs)) {
    out.push(`typedef ${sdecl.is_union ? "union" : "struct"} ${sname} {`);
    for (const f of sdecl.fields) {
      const mArr = /^\[(\d+)\](.+)$/.exec(f.ty);
      if (mArr) out.push(`    ${mapCType(mArr[2])} ${f.name}[${mArr[1]}];`);
      else if (f.bit_width !== null) out.push(`    ${mapCType(f.ty)} ${f.name} : ${f.bit_width};`);
      else out.push(`    ${mapCType(f.ty)} ${f.name};`);
    }
    out.push(`} ${sname};`, "", `static inline void ${sname}_check_invariant(const ${sname}* self, const char* fn_ctx) {`);
    if (!sdecl.is_union) {
      for (const inv of sdecl.invariants) {
        const cInv = translateExpr(inv, ast, null, null, new Set(["self"]), {});
        out.push(`    if (!(${cInv})) jn_contract_fail("invariant (${sname})", fn_ctx, "${inv.replaceAll('"', '\\"')}");`);
      }
    }
    out.push("}", "");
  }

  for (const [tname, tdecl] of Object.entries(ast.traits)) {
    out.push("typedef struct {");
    for (const [tmName, tmSpec] of Object.entries(tdecl.methods)) {
      const fpParams = ["void* self", ...tmSpec.params.filter((p) => p.name !== "self").map((p) => `${mapCType(p.ty)} ${p.name}`)];
      out.push(`    ${mapCType(tmSpec.ret_ty)} (*${tmName})(${fpParams.join(", ")});`);
    }
    out.push(`} JnVTable_${tname};`, `typedef struct { void* data; const JnVTable_${tname}* vtable; } JnDyn_${tname};`, `_Static_assert(sizeof(JnDyn_${tname}) == 16, "JnDyn_${tname} must be 16-byte fat pointer");`, "");
  }

  for (const fspec of Object.values(ast.functions)) {
    if (!fspec.is_spin_variadic && fspec.err_ty) {
      out.push(`typedef struct { bool is_err; JnAnyError err; ${mapCType(fspec.ret_ty)} val; } ${resultTypedefName(fspec)};`);
    }
  }
  out.push("");

  for (const fspec of Object.values(ast.functions)) {
    if (fspec.is_spin_variadic) continue;
    const retC = fspec.err_ty ? resultTypedefName(fspec) : mapCType(fspec.ret_ty);
    const cParams = fspec.params.map((p) => {
      if (p.name === "self") return p.mode === "mut" ? `${p.ty}* JN_RESTRICT self` : `const ${p.ty}* self`;
      if (isStructPtrType(p.ty)) return `${mapCType(p.ty)} ${p.name}`;
      if (p.mode === "mut" && (p.ty === "Arena" || p.ty in ast.structs)) return `${mapCType(p.ty)}* JN_RESTRICT ${p.name}`;
      return `${mapCType(p.ty)} ${p.name}`;
    });
    out.push(`${retC} ${cFnName(fspec)}(${cParams.length > 0 ? cParams.join(", ") : "void"});`);
  }
  out.push("");

  for (const [tname, tdecl] of Object.entries(ast.traits)) {
    for (const sname of Object.keys(ast.structs)) {
      if (Object.keys(tdecl.methods).every((tmName) => `${sname}.${tmName}` in ast.functions)) {
        out.push(`static const JnVTable_${tname} JnVTable_${tname}_for_${sname} = {`);
        for (const tmName of Object.keys(tdecl.methods)) out.push(`    .${tmName} = (void*)${sname}_${tmName},`);
        out.push("};", "");
      }
    }
  }

  const liftedClosuresDefs: string[] = [];
  let closureSeq = 0;
  const headerInsertIdx = out.length;

  function synthesizeClosureLiteral(
    closureExpr: string,
    fspec: FnSpec,
    ptrVars: Set<string>,
    varTypes: Record<string, string>,
    ownBoxParams: string[],
    localOwnedBoxes: string[],
  ): [string[], string, string] | null {
    const mCl = /^(\*|\^)?fn(?:\[([^\]]*)\])?\(\s*([A-Za-z_][A-Za-z0-9_]*)(?:\s*:\s*[A-Za-z0-9_]+)?\s*\)(?:\s*->\s*[A-Za-z0-9_]+)?\s*=>\s*(.+)$/.exec(closureExpr.trim());
    if (!mCl) return null;
    const [track, capListRaw, cParam, cBodyRaw] = [mCl[1] || "", mCl[2] || "", mCl[3], mCl[4].trim()];
    const ownCaps = [...capListRaw.matchAll(/\bown\s+([A-Za-z_][A-Za-z0-9_]*)\b/g)].map((m) => m[1]);
    for (const oc of ownCaps) {
      removeFromList(ownBoxParams, oc);
      removeFromList(localOwnedBoxes, oc);
    }
    const paramTyMap: Record<string, string> = {};
    for (const p of fspec.params) paramTyMap[p.name] = p.ty;
    const capturedVars: [string, string][] = [];
    for (const [vname, vty] of Object.entries(varTypes)) {
      if (vname !== cParam && (new RegExp(`\\b${vname}\\b`).test(cBodyRaw) || ownCaps.includes(vname))) {
        const origTy = vname in paramTyMap ? paramTyMap[vname] : ptrVars.has(vname) && vty in ast.structs ? `*${vty}` : vty;
        capturedVars.push([vname, mapCType(origTy)]);
      }
    }
    const cid = closureSeq++;
    liftedClosuresDefs.push(`typedef struct _JnClosureEnv_${cid} {`);
    if (capturedVars.length > 0) for (const [cvName, cvCty] of capturedVars) liftedClosuresDefs.push(`    ${cvCty} ${cvName};`);
    else liftedClosuresDefs.push("    int64_t _unused;");
    liftedClosuresDefs.push(`} _JnClosureEnv_${cid};`);

    let cBodyTrans = translateExpr(cBodyRaw, ast, fspec, null, ptrVars, varTypes);
    for (const [cvName] of capturedVars) cBodyTrans = cBodyTrans.replace(new RegExp(`\\b${cvName}\\b`, "g"), `_env->${cvName}`);

    liftedClosuresDefs.push(
      `static int64_t _jn_closure_call_${cid}(const void* _raw_env, int64_t ${cParam}) {`,
      `    const _JnClosureEnv_${cid}* _env = (const _JnClosureEnv_${cid}*)_raw_env; (void)_env; return ${cBodyTrans};`,
      "}",
    );
    if (track === "*") {
      liftedClosuresDefs.push(
        `static void _jn_closure_drop_${cid}(void* _raw_env) {`,
        `    if (!_raw_env) return; _JnClosureEnv_${cid}* _env = (_JnClosureEnv_${cid}*)_raw_env;`,
        ...ownCaps.map((oc) => `    jn_box_free(_env->${oc});`),
        "    jn_box_free(_env); }",
      );
    }
    liftedClosuresDefs.push("");
    const envInits = capturedVars.length > 0 ? capturedVars.map(([cvName]) => `.${cvName} = ${cvName}`).join(", ") : "._unused = 0";
    if (track === "*") {
      return [
        [`    _JnClosureEnv_${cid}* _cenv_${cid} = (_JnClosureEnv_${cid}*)jn_box_alloc(sizeof(_JnClosureEnv_${cid}));`, `    *_cenv_${cid} = (_JnClosureEnv_${cid}){ ${envInits} };`],
        `((JnBoxFn_i64_to_i64){ .env = _cenv_${cid}, .call = _jn_closure_call_${cid}, .drop_env = _jn_closure_drop_${cid} })`,
        "*fn(i64) -> i64",
      ];
    }
    if (track === "^") {
      return [
        [`    _JnClosureEnv_${cid}* _cenv_${cid} = (_JnClosureEnv_${cid}*)jn_gc_alloc(sizeof(_JnClosureEnv_${cid}));`, `    *_cenv_${cid} = (_JnClosureEnv_${cid}){ ${envInits} };`],
        `((JnGcFn_i64_to_i64){ .env = _cenv_${cid}, .call = _jn_closure_call_${cid} })`,
        "^fn(i64) -> i64",
      ];
    }
    return [
      [`    _JnClosureEnv_${cid} _cenv_${cid} = (_JnClosureEnv_${cid}){ ${envInits} };`],
      `((JnFn_i64_to_i64){ .env = &_cenv_${cid}, .call = _jn_closure_call_${cid} })`,
      "fn(i64) -> i64",
    ];
  }

  for (const [key, fspec] of Object.entries(ast.functions)) {
    if (fspec.is_spin_variadic) continue;
    const cname = cFnName(fspec);
    const retC = fspec.err_ty ? resultTypedefName(fspec) : mapCType(fspec.ret_ty);
    const ptrVars = new Set<string>();
    const varTypes: Record<string, string> = {};
    const ownBoxParams: string[] = [];
    const ownBoxFnParams: string[] = [];
    const cParams: string[] = [];

    for (const p of fspec.params) {
      varTypes[p.name] = p.ty.startsWith("dyn ") || isClosureType(p.ty) ? p.ty : stripPtrAndOpt(p.ty);
      if (p.name === "self") {
        ptrVars.add("self");
        cParams.push(p.mode === "mut" ? `${p.ty}* JN_RESTRICT self` : `const ${p.ty}* self`);
        if (p.mode === "own") ownBoxParams.push("self");
      } else if (isStructPtrType(p.ty)) {
        ptrVars.add(p.name);
        cParams.push(`${mapCType(p.ty)} ${p.name}`);
        if (p.mode === "own" && p.ty.startsWith("*")) ownBoxParams.push(p.name);
      } else if (isClosureType(p.ty)) {
        cParams.push(`${mapCType(p.ty)} ${p.name}`);
        if (p.mode === "own" && p.ty.startsWith("*fn(")) ownBoxFnParams.push(p.name);
      } else if (p.mode === "mut" && (p.ty === "Arena" || p.ty in ast.structs)) {
        ptrVars.add(p.name);
        cParams.push(`${mapCType(p.ty)}* JN_RESTRICT ${p.name}`);
      } else {
        cParams.push(`${mapCType(p.ty)} ${p.name}`);
      }
    }
    out.push(`${retC} ${cname}(${cParams.length > 0 ? cParams.join(", ") : "void"}) {`);

    for (const p of fspec.params) {
      const baseS = stripPtrAndOpt(p.ty);
      if (baseS in ast.structs) {
        out.push(ptrVars.has(p.name) ? `    if (${p.name}) ${baseS}_check_invariant(${p.name}, "${key}:entry");` : `    ${baseS}_check_invariant(&${p.name}, "${key}:entry");`);
      }
    }

    for (let reqIdx = 0; reqIdx < fspec.requires.length; reqIdx++) {
      const req = fspec.requires[reqIdx];
      const cCond = translateExpr(req.cond, ast, fspec, null, ptrVars, varTypes);
      if (req.else_err && fspec.err_ty) {
        const cErr = translateExpr(req.else_err, ast, fspec, null, ptrVars, varTypes);
        out.push(`    if (!(${cCond})) {`, ...ownBoxParams.map((obp) => `        jn_box_free(${obp});`), ...ownBoxFnParams.map((obf) => `        jn_box_fn_drop(&${obf});`), `        JnAnyError _e = jn_err_raise(${cErr}, 0, "${ast.name}", "${key}", ${reqIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _e };`, "    }");
      } else {
        out.push(`    if (!(${cCond})) jn_contract_fail("requires", "${key}", "${req.cond.replaceAll('"', '\\"')}");`);
      }
    }

    const oldMap: Record<string, string> = {};
    for (const ens of fspec.ensures) {
      for (const mOld of ens.matchAll(/old\((?:\s*([^()]+(?:\([^()]*\))?)\s*)\)/g)) {
        const origExpr = mOld[1].trim();
        if (!(origExpr in oldMap)) {
          const snapName = `_old_${Object.keys(oldMap).length}`;
          oldMap[origExpr] = snapName;
          out.push(`    int64_t ${snapName} = (int64_t)(${translateExpr(origExpr, ast, fspec, null, ptrVars, varTypes)});`);
        }
      }
    }

    const localOwnedBoxes: string[] = [];
    const emitExitChecks = (resultVar: string | null): string[] => {
      const checks: string[] = [];
      for (const obp of ownBoxParams) if (!fspec.body_lines.some((bl) => bl.includes(`jn_box_free(${obp})`))) checks.push(`    jn_box_free(${obp});`);
      for (const obf of ownBoxFnParams) checks.push(`    jn_box_fn_drop(&${obf});`);
      for (const lbox of localOwnedBoxes) if (lbox !== resultVar && !fspec.body_lines.some((bl) => bl.includes(`jn_box_free(${lbox})`))) checks.push(`    jn_box_free(${lbox});`);
      if (ptrVars.has("self") && fspec.struct_owner && fspec.struct_owner in ast.structs && !ownBoxParams.includes("self")) checks.push(`    ${fspec.struct_owner}_check_invariant(self, "${key}:exit");`);
      const retBase = stripPtrAndOpt(fspec.ret_ty);
      if (resultVar) varTypes[resultVar] = retBase;
      if (resultVar && retBase in ast.structs) {
        checks.push(fspec.ret_ty.startsWith("*") || fspec.ret_ty.startsWith("^") ? `    ${retBase}_check_invariant(${resultVar}, "${key}:return");` : `    ${retBase}_check_invariant(&${resultVar}, "${key}:return");`);
      }
      for (const ens of fspec.ensures) checks.push(`    if (!(${translateExpr(ens, ast, fspec, oldMap, ptrVars, varTypes)})) jn_contract_fail("ensures", "${key}", "${ens.replaceAll('"', '\\"')}");`);
      return checks;
    };

    const rawBlines = fspec.body_lines.map((l) => l.trim()).filter((l) => l.length > 0);
    const blines: string[] = [];
    let kIdx = 0;
    while (kIdx < rawBlines.length) {
      let curL = rawBlines[kIdx];
      if (/\bcatch\s+[A-Za-z0-9_]+\s*\{$/.test(curL) && kIdx + 2 < rawBlines.length && rawBlines[kIdx + 2].startsWith("}")) {
        blines.push(`${curL} ${rawBlines[kIdx + 1]} }`);
        kIdx += 3;
        continue;
      }
      if (/^(?:return\s+)?match\s+.+\{$/.test(curL)) {
        const accParts = [curL];
        kIdx += 1;
        while (kIdx < rawBlines.length) {
          const part = rawBlines[kIdx++];
          accParts.push(part);
          if (part === "}" || part === "};") break;
        }
        blines.push("return " + accParts.join(" "));
        continue;
      }
      if (/^(?:val|var|let(?:\s+mut)?)\s+[A-Za-z0-9_:]+\s*=\s*if\b/.test(curL) && curL.endsWith("{")) {
        const accParts = [curL];
        kIdx += 1;
        while (kIdx < rawBlines.length) {
          const part = rawBlines[kIdx++];
          accParts.push(part);
          if ((part === "}" || part === "};") && (kIdx >= rawBlines.length || !rawBlines[kIdx].startsWith("else"))) break;
        }
        blines.push(accParts.join(" "));
        continue;
      }
      if (curL.includes("*in(Arena.new(") && !fspec.params.some((p) => p.ty === "Arena")) curL = curL.replace(/\*in\(Arena\.new\([^)]*\)\)\s*/g, "*");
      const mMlLit = /^(?:return\s+|(?:val|var)\s+[A-Za-z0-9_:]+\s*=\s*)?(?:\*in\([A-Za-z0-9_]+\)\s*|\*|\^)?([A-Za-z0-9_]+)\s*\{$/.exec(curL);
      if (mMlLit && mMlLit[1] in ast.structs) {
        const accParts = [curL];
        kIdx += 1;
        while (kIdx < rawBlines.length) {
          const part = rawBlines[kIdx++];
          accParts.push(part);
          if (part === "}" || part === "};") break;
        }
        blines.push(accParts.join(" "));
        continue;
      }
      if (curL.endsWith("(") && !curL.endsWith("{")) {
        const accParts = [curL];
        kIdx += 1;
        while (kIdx < rawBlines.length) {
          const part = rawBlines[kIdx++];
          accParts.push(part);
          if (part.startsWith(")")) break;
        }
        blines.push(accParts.join(" "));
        continue;
      }
      blines.push(curL);
      kIdx += 1;
    }

    const declaredLocals = new Set<string>();
    for (let bIdx = 0; bIdx < blines.length; bIdx++) {
      let stmt = blines[bIdx].replace(/\b[A-Za-z0-9_]+::([A-Za-z0-9_]+)\s*\(/g, "$1(");
      if (stmt.includes(".alloc_count()") && stmt.includes("+=")) continue;
      for (const mOwnUse of stmt.matchAll(/\bown\s+([A-Za-z_][A-Za-z0-9_]*)\b/g)) removeFromList(localOwnedBoxes, mOwnUse[1]);

      const mIf1lineRet = /^if\s+(.+?)\s*\{\s*return\s+(.+?)\s*\}$/.exec(stmt);
      if (mIf1lineRet) {
        const cCond = translateExpr(mIf1lineRet[1].trim(), ast, fspec, null, ptrVars, varTypes);
        const cRet = translateExpr(mIf1lineRet[2].trim(), ast, fspec, null, ptrVars, varTypes);
        out.push(`    if (${cCond}) {`, `        ${mapCType(fspec.ret_ty)} result = ${cRet};`, ...emitExitChecks("result").map((l) => "    " + l), fspec.err_ty ? `        return (${retC}){ .is_err = false, .val = result };` : "        return result;", "    }");
        continue;
      }

      const mGuard1line = /^guard\s+(.+?)\s+else\s*(?:\{\s*raise\s+(.+?)\s*\}|([A-Za-z0-9_.]+))$/.exec(stmt);
      if (mGuard1line) {
        const cCond = translateExpr(mGuard1line[1].trim(), ast, fspec, null, ptrVars, varTypes);
        const cErr = translateExpr((mGuard1line[2] || mGuard1line[3]).trim(), ast, fspec, null, ptrVars, varTypes);
        out.push(`    if (!(${cCond})) {`, ...localOwnedBoxes.map((lbox) => `        jn_box_free(${lbox});`), `        JnAnyError _e = jn_err_raise(${cErr}, 0, "${ast.name}", "${key}", ${bIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _e };`, "    }");
        continue;
      }

      if (stmt.startsWith("guard ") && stmt.endsWith("else {")) {
        const gCond = stmt.slice("guard ".length, -"else {".length).trim();
        const innerStmt = blines[++bIdx];
        if (bIdx + 1 < blines.length && blines[bIdx + 1] === "}") bIdx += 1;
        const mRaise = /^raise\s+(.+)$/.exec(innerStmt);
        if (!mRaise) throw new Error(`Expected raise inside guard else: ${innerStmt}`);
        const cCond = translateExpr(gCond, ast, fspec, null, ptrVars, varTypes);
        const cErr = translateExpr(mRaise[1], ast, fspec, null, ptrVars, varTypes);
        out.push(`    if (!(${cCond})) {`, ...localOwnedBoxes.map((lbox) => `        jn_box_free(${lbox});`), `        JnAnyError _e = jn_err_raise(${cErr}, 0, "${ast.name}", "${key}", ${bIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _e };`, "    }");
        continue;
      }

      const mCatch = /^(?:val|var)\s+([A-Za-z0-9_]+)\s*=\s*(.+?)\s+catch\s+([A-Za-z0-9_]+)\s*\{\s*(.+?)\?\s*\}$/.exec(stmt);
      if (mCatch) {
        const [vname, primExpr, fbExpr] = [mCatch[1], mCatch[2].trim(), mCatch[4].trim()];
        const [primSpec, fbSpec] = [ast.functions[primExpr.split("(")[0].trim()], ast.functions[fbExpr.split("(")[0].trim()]];
        const [cPrim, cFb] = [translateExpr(primExpr, ast, fspec, null, ptrVars, varTypes), translateExpr(fbExpr, ast, fspec, null, ptrVars, varTypes)];
        out.push(`    ${mapCType(primSpec.ret_ty)} ${vname};`, `    ${resultTypedefName(primSpec)} _prim_${vname} = ${cPrim};`, `    if (!_prim_${vname}.is_err) { ${vname} = _prim_${vname}.val; } else {`, `        ${resultTypedefName(fbSpec)} _fb_${vname} = ${cFb};`, `        if (_fb_${vname}.is_err) {`, ...localOwnedBoxes.map((lbox) => `            jn_box_free(${lbox});`), `            JnAnyError _pe = jn_err_propagate(_fb_${vname}.err, "${ast.name}", "${key}", ${bIdx + 1});`, `            return (${retC}){ .is_err = true, .err = _pe };`, "        }", `        ${vname} = _fb_${vname}.val;`, "    }");
        continue;
      }

      if (stmt.startsWith("if ") && stmt.endsWith("{")) {
        out.push(`    if (${translateExpr(stmt.slice(3, -1).trim(), ast, fspec, null, ptrVars, varTypes)}) {`);
        continue;
      }
      if ((stmt.startsWith("} else if ") || stmt.startsWith("else if ")) && stmt.endsWith("{")) {
        const prefix = stmt.startsWith("} else if ") ? "} else if " : "else if ";
        out.push(`    ${prefix.trim()} (${translateExpr(stmt.slice(prefix.length, -1).trim(), ast, fspec, null, ptrVars, varTypes)}) {`);
        continue;
      }
      if (stmt === "} else {" || stmt === "else {" || stmt === "}") {
        out.push(`    ${stmt}`);
        continue;
      }
      if (stmt.startsWith("while ") && stmt.endsWith("{")) {
        out.push(`    while (${translateExpr(stmt.slice(6, -1).trim(), ast, fspec, null, ptrVars, varTypes)}) {`);
        continue;
      }
      const mForRange = /^for\s+([A-Za-z_][A-Za-z0-9_]*)\s+in\s+(.+?)\.\.(.+?)\s*\{$/.exec(stmt);
      if (mForRange) {
        out.push(`    for (int64_t ${mForRange[1]} = ${translateExpr(mForRange[2].trim(), ast, fspec, null, ptrVars, varTypes)}; ${mForRange[1]} < ${translateExpr(mForRange[3].trim(), ast, fspec, null, ptrVars, varTypes)}; ${mForRange[1]}++) {`);
        continue;
      }

      if (stmt.startsWith("return raise ")) stmt = "raise " + stmt.slice("return raise ".length).trim();
      if (stmt.startsWith("raise ")) {
        const cErr = translateExpr(stmt.slice(6).trim(), ast, fspec, null, ptrVars, varTypes);
        out.push(...localOwnedBoxes.map((lbox) => `    jn_box_free(${lbox});`), `    JnAnyError _e = jn_err_raise(${cErr}, 0, "${ast.name}", "${key}", ${bIdx + 1});`, `    return (${retC}){ .is_err = true, .err = _e };`);
        continue;
      }

      if (stmt === "return") {
        out.push(...emitExitChecks(null), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = 0 };` : "    return 0;");
        continue;
      }

      const mRetArenaVar = /^return\s+\*in\(([A-Za-z0-9_]+)\)\s+([A-Za-z_][A-Za-z0-9_]*)$/.exec(stmt);
      if (mRetArenaVar && mRetArenaVar[2] in varTypes) {
        const [arenaVar, srcVar, sname] = [mRetArenaVar[1], mRetArenaVar[2], varTypes[mRetArenaVar[2]]];
        ptrVars.add("result");
        out.push(`    ${sname}* result = (${sname}*)jn_arena_alloc(${ptrVars.has(arenaVar) ? arenaVar : `&${arenaVar}`}, sizeof(${sname}));`, `    *result = ${srcVar};`, ...emitExitChecks("result"), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = result };` : "    return result;");
        continue;
      }

      const mRetStruct = /^(?:return\s+)?(\*in\(([A-Za-z0-9_]+)\)\s*|\*|\^)?([A-Za-z0-9_]+)\s*\{(.*)\}$/.exec(stmt);
      if (mRetStruct && mRetStruct[3] in ast.structs) {
        const [allocPrefix, arenaVar, sname] = [(mRetStruct[1] || "").trim(), mRetStruct[2], mRetStruct[3]];
        const finits = parseStructFieldInits(mRetStruct[4], ast, fspec, ptrVars, sname, varTypes);
        if (allocPrefix === "*") {
          out.push(`    ${sname}* result = (${sname}*)jn_box_alloc(sizeof(${sname})); *result = (${sname}){ ${finits} };`);
          ptrVars.add("result");
        } else if (allocPrefix.startsWith("*in(")) {
          out.push(`    ${sname}* result = (${sname}*)jn_arena_alloc(${ptrVars.has(arenaVar) ? arenaVar : `&${arenaVar}`}, sizeof(${sname})); *result = (${sname}){ ${finits} };`);
          ptrVars.add("result");
        } else if (allocPrefix === "^") {
          out.push(`    ${sname}* result = (${sname}*)jn_gc_alloc(sizeof(${sname})); *result = (${sname}){ ${finits} };`);
          ptrVars.add("result");
        } else {
          out.push(`    ${sname} result = (${sname}){ ${finits} };`);
        }
        out.push(...emitExitChecks("result"), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = result };` : "    return result;");
        continue;
      }

      if (stmt.startsWith("return ")) {
        const retExpr = stmt.slice(7).trim();
        const closSynth = synthesizeClosureLiteral(retExpr, fspec, ptrVars, varTypes, ownBoxParams, localOwnedBoxes);
        if (closSynth) {
          out.push(...closSynth[0], `    ${mapCType(fspec.ret_ty)} result = ${closSynth[1]};`, ...emitExitChecks("result"), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = result };` : "    return result;");
          continue;
        }
        if (retExpr.endsWith("?")) {
          const cCall = translateExpr(retExpr.slice(0, -1).trim(), ast, fspec, null, ptrVars, varTypes);
          const calledFnName = cCall.split("(")[0].trim();
          const calledSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === calledFnName) ?? ast.functions[calledFnName];
          const rtryVar = `_ret_try_${bIdx}`;
          if (isStructPtrType(fspec.ret_ty)) ptrVars.add("result");
          out.push(`    ${resultTypedefName(calledSpec)} ${rtryVar} = ${cCall};`, `    if (${rtryVar}.is_err) {`, ...localOwnedBoxes.map((lbox) => `        jn_box_free(${lbox});`), `        JnAnyError _pe = jn_err_propagate(${rtryVar}.err, "${ast.name}", "${key}", ${bIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _pe };`, "    }", `    ${mapCType(fspec.ret_ty)} result = ${rtryVar}.val;`, ...emitExitChecks("result"), `    return (${retC}){ .is_err = false, .val = result };`);
          continue;
        }
        if (retExpr.includes(".") && retExpr.split(".")[0] in ast.enums && fspec.err_ty) {
          const cErr = translateExpr(retExpr, ast, fspec, null, ptrVars, varTypes);
          out.push(...localOwnedBoxes.map((lbox) => `    jn_box_free(${lbox});`), `    JnAnyError _e = jn_err_raise(${cErr}, 0, "${ast.name}", "${key}", ${bIdx + 1});`, `    return (${retC}){ .is_err = true, .err = _e };`);
          continue;
        }
        removeFromList(localOwnedBoxes, retExpr);
        const cRet = translateExpr(retExpr, ast, fspec, null, ptrVars, varTypes);
        if (declaredLocals.has("result")) {
          if (cRet !== "result") out.push(`    result = ${cRet};`);
        } else {
          out.push(`    ${mapCType(fspec.ret_ty)} result = ${cRet};`);
        }
        if (isStructPtrType(fspec.ret_ty)) ptrVars.add("result");
        out.push(...emitExitChecks("result"), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = result };` : "    return result;");
        continue;
      }

      if ((stmt.endsWith("?") || stmt.endsWith("!")) && !/^(?:val|var)\s+/.test(stmt)) {
        const isUnwrap = stmt.endsWith("!");
        const cCall = translateExpr(stmt.slice(0, -1).trim(), ast, fspec, null, ptrVars, varTypes);
        const calledFnName = cCall.split("(")[0].trim();
        const calledSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === calledFnName) ?? ast.functions[calledFnName];
        const tvar = `_try_stmt_${bIdx}`;
        out.push(`    ${resultTypedefName(calledSpec)} ${tvar} = ${cCall};`, `    if (${tvar}.is_err) {`, ...localOwnedBoxes.map((lbox) => `        jn_box_free(${lbox});`), ...(!isUnwrap && fspec.err_ty ? [`        JnAnyError _pe = jn_err_propagate(${tvar}.err, "${ast.name}", "${key}", ${bIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _pe };`] : [`        jn_contract_fail("unwrap_err", "${key}", "${calledFnName}");`]), "    }");
        continue;
      }

      const mTry = /^(?:val|var)\s+([A-Za-z0-9_]+)\s*=\s*(.+?)[?!]$/.exec(stmt);
      if (mTry) {
        const vname = mTry[1] === "_" ? `_ign_${bIdx}` : mTry[1];
        const alreadyDecl = declaredLocals.has(vname);
        declaredLocals.add(vname);
        const cCall = translateExpr(mTry[2].trim(), ast, fspec, null, ptrVars, varTypes);
        const calledFnName = cCall.split("(")[0].trim();
        const calledSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === calledFnName) ?? ast.functions[calledFnName];
        const calledValTy = mapCType(calledSpec.ret_ty);
        if (!calledSpec.err_ty) {
          out.push(alreadyDecl ? `    ${vname} = ${cCall};` : `    ${calledValTy} ${vname} = ${cCall};`);
        } else {
          const tname = `_try_${vname}_${bIdx}`;
          out.push(`    ${resultTypedefName(calledSpec)} ${tname} = ${cCall};`, `    if (${tname}.is_err) {`, ...localOwnedBoxes.map((lbox) => `        jn_box_free(${lbox});`), ...(fspec.err_ty ? [`        JnAnyError _pe = jn_err_propagate(${tname}.err, "${ast.name}", "${key}", ${bIdx + 1});`, `        return (${retC}){ .is_err = true, .err = _pe };`] : [`        jn_contract_fail("unwrap_err", "${key}", "${vname}");`]), "    }", alreadyDecl ? `    ${vname} = ${tname}.val;` : `    ${calledValTy} ${vname} = ${tname}.val;`);
        }
        varTypes[vname] = isClosureType(calledSpec.ret_ty) ? calledSpec.ret_ty : stripPtrAndOpt(calledSpec.ret_ty);
        if (isStructPtrType(calledSpec.ret_ty)) {
          ptrVars.add(vname);
          if (calledSpec.ret_ty.startsWith("*") && !calledSpec.params.some((p) => p.ty === "Arena")) localOwnedBoxes.push(vname);
        }
        continue;
      }

      const mDeclStruct = /^(?:val|var)\s+([A-Za-z0-9_]+)(?:\s*:\s*[^=]+)?\s*=\s*(\*in\(([A-Za-z0-9_]+)\)\s*|\*|\^)?([A-Za-z0-9_]+)\s*\{(.*)\}$/.exec(stmt);
      if (mDeclStruct && mDeclStruct[4] in ast.structs) {
        const [vname, allocPrefix, arenaVar, sname] = [mDeclStruct[1], (mDeclStruct[2] || "").trim(), mDeclStruct[3], mDeclStruct[4]];
        declaredLocals.add(vname);
        varTypes[vname] = sname;
        const finits = parseStructFieldInits(mDeclStruct[5], ast, fspec, ptrVars, sname, varTypes);
        if (allocPrefix === "*") {
          out.push(`    ${sname}* ${vname} = (${sname}*)jn_box_alloc(sizeof(${sname})); *${vname} = (${sname}){ ${finits} };`);
          ptrVars.add(vname);
          localOwnedBoxes.push(vname);
        } else if (allocPrefix.startsWith("*in(")) {
          out.push(`    ${sname}* ${vname} = (${sname}*)jn_arena_alloc(${ptrVars.has(arenaVar) ? arenaVar : `&${arenaVar}`}, sizeof(${sname})); *${vname} = (${sname}){ ${finits} };`);
          ptrVars.add(vname);
        } else if (allocPrefix === "^") {
          out.push(`    ${sname}* ${vname} = (${sname}*)jn_gc_alloc(sizeof(${sname})); *${vname} = (${sname}){ ${finits} };`);
          ptrVars.add(vname);
        } else {
          out.push(`    ${sname} ${vname} = (${sname}){ ${finits} };`);
        }
        continue;
      }

      const mDecl = /^(?:val|var)\s+([A-Za-z0-9_]+)(?:\s*:\s*([^=]+))?\s*=\s*(.+)$/.exec(stmt);
      if (mDecl) {
        const vname = mDecl[1] === "_" ? `_ign_${bIdx}` : mDecl[1];
        declaredLocals.add(vname);
        const [explTy, rhs] = [mDecl[2] ? mDecl[2].trim() : null, mDecl[3].trim()];
        const closSynth = synthesizeClosureLiteral(rhs, fspec, ptrVars, varTypes, ownBoxParams, localOwnedBoxes);
        if (closSynth) {
          varTypes[vname] = closSynth[2];
          out.push(...closSynth[0], `    ${mapCType(closSynth[2])} ${vname} = ${closSynth[1]};`);
          continue;
        }
        const cRhs = translateExpr(rhs, ast, fspec, null, ptrVars, varTypes);
        const fnPrefix = cRhs.split("(")[0].trim();
        const matchedSpec = Object.values(ast.functions).find((fs) => cFnName(fs) === fnPrefix) ?? null;
        let cTy = "int64_t";
        if (explTy) {
          cTy = mapCType(explTy);
          varTypes[vname] = isClosureType(explTy) ? explTy : stripPtrAndOpt(explTy);
          if (isStructPtrType(explTy)) ptrVars.add(vname);
        } else if (rhs.startsWith("Arena.new")) {
          cTy = "JnArena";
          varTypes[vname] = "Arena";
        } else if (matchedSpec) {
          cTy = mapCType(matchedSpec.ret_ty);
          varTypes[vname] = isClosureType(matchedSpec.ret_ty) ? matchedSpec.ret_ty : stripPtrAndOpt(matchedSpec.ret_ty);
          if (isStructPtrType(matchedSpec.ret_ty)) {
            ptrVars.add(vname);
            if (matchedSpec.ret_ty.startsWith("*") && !matchedSpec.params.some((p) => p.ty === "Arena")) localOwnedBoxes.push(vname);
          }
        } else if (cRhs.startsWith("((JnTuple_i64_FmtSpec_i64)")) {
          cTy = "JnTuple_i64_FmtSpec_i64";
          varTypes[vname] = "(i64, FmtSpec, i64)";
        } else if (cRhs.startsWith("((JnTuple_i64_FmtSpec)")) {
          cTy = "JnTuple_i64_FmtSpec";
          varTypes[vname] = "(i64, FmtSpec)";
        } else if (cRhs.startsWith("JnString_") || cRhs.startsWith("jn_raw_to_sso_string") || cRhs.startsWith("jn_fmt_end(") || cRhs.startsWith("rt_raw_to_sso_string")) {
          cTy = "JnString";
          varTypes[vname] = "String";
        } else if ((cRhs.includes("jn_mk_str(") || cRhs.startsWith("jn_str_sub(") || cRhs.startsWith("jn_str_slice(")) && !cRhs.startsWith("jn_raw_") && !cRhs.startsWith("jn_string_") && !cRhs.startsWith("jn_str_eq(") && !cRhs.startsWith("rt_raw_")) {
          cTy = "jn_str";
          varTypes[vname] = "str";
        } else if (!rhs.startsWith("if ") && (cRhs === "true" || cRhs === "false" || rhs.includes("==") || rhs.includes("||") || rhs.includes("&&"))) {
          cTy = "bool";
        } else if (cRhs.includes("self->data")) {
          cTy = "int32_t";
        }
        out.push(`    ${cTy} ${vname} = ${cRhs};`);
        continue;
      }

      if (stmt.startsWith("requires ") || stmt.startsWith("ensures ")) continue;

      if ((bIdx === blines.length - 1 || blines[bIdx + 1].startsWith("}")) && fspec.ret_ty !== "void" && !stmt.replaceAll("==", "").replaceAll("!=", "").replaceAll("<=", "").replaceAll(">=", "").includes("=")) {
        const cRet = translateExpr(stmt, ast, fspec, null, ptrVars, varTypes);
        out.push(`    { ${mapCType(fspec.ret_ty)} result = ${cRet};`, ...emitExitChecks("result"), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = result }; }` : "    return result; }");
        continue;
      }

      out.push(`    ${translateExpr(stmt, ast, fspec, null, ptrVars, varTypes)};`);
    }

    if (fspec.ret_ty === "void") {
      out.push(...emitExitChecks(null), fspec.err_ty ? `    return (${retC}){ .is_err = false, .val = 0 };` : "    return 0;");
    }
    out.push("}", "");
  }

  emitExampleRunnersAndFuzzSuite(ast, out, headerInsertIdx, liftedClosuresDefs);
  return out.join("\n");
}
